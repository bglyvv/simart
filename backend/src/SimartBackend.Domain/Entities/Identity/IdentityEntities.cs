using SimartBackend.Domain.Common;

namespace SimartBackend.Domain.Entities.Identity;

/// <summary>The account; everything else hangs off it.</summary>
public class Family : ISoftDeletable
{
    public Guid Id { get; set; }
    public DateTimeOffset CreatedAt { get; set; }

    public bool IsDeleted { get; set; }
    public DateTimeOffset? DeletedAt { get; set; }
    public Guid? DeletedBy { get; set; }

    public ICollection<Parent> Parents { get; set; } = new List<Parent>();
    public ICollection<Child> Children { get; set; } = new List<Child>();
}

/// <summary>Email/password <em>and</em> the PIN that gates the parent dashboard
/// and settings routes.</summary>
public class Parent : ISoftDeletable
{
    public Guid Id { get; set; }
    public Guid FamilyId { get; set; }
    public required string FullName { get; set; }
    public required string Email { get; set; }
    public required string PasswordHash { get; set; }
    public required string PinHash { get; set; }

    public bool IsDeleted { get; set; }
    public DateTimeOffset? DeletedAt { get; set; }
    public Guid? DeletedBy { get; set; }

    public Family Family { get; set; } = null!;
}

/// <summary>A one-time, time-limited "forgot password" token — never soft-deleted,
/// just consumed (UsedAt set) or left to expire. Only TokenHash is ever stored, not
/// the raw token (that only ever exists in the email and the reset request that
/// redeems it) — a SHA-256 hash is enough here since this is a high-entropy random
/// value generated by us, not a low-entropy guessable password.</summary>
public class PasswordResetToken
{
    public Guid Id { get; set; }
    public Guid ParentId { get; set; }
    public required string TokenHash { get; set; }
    public DateTimeOffset ExpiresAt { get; set; }
    public DateTimeOffset? UsedAt { get; set; }
    public DateTimeOffset CreatedAt { get; set; }

    public Parent Parent { get; set; } = null!;
}

/// <summary>One row per child profile — a family can hold several.</summary>
public class Child : ISoftDeletable
{
    public Guid Id { get; set; }
    public Guid FamilyId { get; set; }
    public required string Name { get; set; }
    public required string AvatarEmoji { get; set; }
    public required string Gender { get; set; }
    public DateOnly DateOfBirth { get; set; }
    public required string City { get; set; }

    /// <summary>Null until a parent sets one (opt-in, not required for every
    /// child) — gates one sibling switching into another's account from the
    /// family gate or the in-app child switcher. Unlike Parent.PinHash, this
    /// is set by the parent on the child's behalf, never self-service, and
    /// there's no "change my own PIN" flow for a child — see
    /// SetChildPinCommand/VerifyChildPinQuery.</summary>
    public string? PinHash { get; set; }

    public bool IsDeleted { get; set; }
    public DateTimeOffset? DeletedAt { get; set; }
    public Guid? DeletedBy { get; set; }

    public Family Family { get; set; } = null!;
}
